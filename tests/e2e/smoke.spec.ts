test("admin publishes and controls homepage campaigns", async ({ page }, testInfo) => {
  const title = `Campaign ${testInfo.project.name}-${Date.now()}`;
  await page.goto("/login?next=%2Fadmin%2Fbanners");
  await page.getByLabel("Email address").fill("admin@yoranzify.local");
  await page.getByLabel("Password", { exact: true }).fill("Yoranzify123!");
  await page.getByRole("button", { name: /Sign in/ }).click();
  await expect(page).toHaveURL(/\/admin\/banners$/);
  const stale = await (await page.request.get("/api/admin/homepage")).json();
  for (const banner of stale.banners.filter((item: { title: string }) => item.title.startsWith(`Campaign ${testInfo.project.name}-`))) await page.request.delete(`/api/admin/homepage/banners/${banner.id}`);
  await page.reload();
  await page.getByRole("button", { name: "New banner" }).click();
  await page.getByLabel("Desktop image").setInputFiles("public/images/yoranzify-hero.png");
  await expect(page.getByText("Image ready").first()).toBeVisible();
  await page.getByLabel("Mobile image").setInputFiles("public/images/yoranzify-hero.png");
  await expect(page.getByText("Image ready")).toHaveCount(2);
  await page.getByLabel("Accessible image description").fill(`${title} editorial model`);
  await page.getByLabel("Headline").fill(title);
  await page.getByLabel("Subtitle").fill("A responsive campaign from the homepage studio.");
  await page.getByRole("button", { name: "Save banner" }).click();
  await expect(page.getByRole("heading", { name: title })).toBeVisible();

  const cms = await (await page.request.get("/api/admin/homepage")).json();
  const created = cms.banners.find((banner: { title: string }) => banner.title === title);
  expect(created).toBeTruthy();
  const secondTitle = `${title} second`;
  const second = await page.request.post("/api/admin/homepage", { data: { kind: "banner", data: { desktopMediaId: created.desktopMediaId, mobileMediaId: created.mobileMediaId, altText: `${secondTitle} editorial model`, title: secondTitle, subtitle: "Second carousel story.", buttonText: "Explore", buttonUrl: "/shop", position: created.position + 1, startsAt: null, endsAt: null, enabled: true } } });
  expect(second.ok()).toBe(true);
  const secondId = (await second.json()).banner.id;

  await page.goto("/");
  const carousel = page.getByRole("region", { name: "Featured collections" });
  const findSlide = async (heading: string) => { for (let attempt = 0; attempt < 12; attempt++) { if (await carousel.getByRole("heading", { name: heading, exact: true }).count()) return; await carousel.getByRole("button", { name: "Next banner" }).click(); } throw new Error(`Carousel did not reach ${heading}`); };
  await findSlide(title);
  await expect(carousel.getByRole("heading", { name: title, exact: true })).toBeVisible();
  await expect(carousel.locator("picture source")).toHaveAttribute("srcset", `/api/media/${created.mobileMediaId}`);
  await findSlide(secondTitle);
  await expect(carousel.getByRole("heading", { name: secondTitle, exact: true })).toBeVisible();
  await expect(carousel.getByRole("button", { name: /carousel/ })).toBeVisible();

  const disabled = await page.request.patch(`/api/admin/homepage/banners/${created.id}`, { data: { desktopMediaId: created.desktopMediaId, mobileMediaId: created.mobileMediaId, altText: created.altText, title: created.title, subtitle: created.subtitle, buttonText: created.buttonText, buttonUrl: created.buttonUrl, position: created.position, startsAt: created.startsAt, endsAt: created.endsAt, enabled: false } });
  expect(disabled.ok()).toBe(true);
  await page.goto("/");
  await expect(page.getByRole("heading", { name: title, exact: true })).toHaveCount(0);

  await page.request.delete(`/api/admin/homepage/banners/${created.id}`);
  await page.request.delete(`/api/admin/homepage/banners/${secondId}`);
  if (testInfo.project.name === "desktop") {
    await page.goto("/admin/banners");
    const testimonials = page.locator(".section-editor article").filter({ hasText: "Testimonials" });
    await testimonials.locator('input[type="checkbox"]').check();
    await page.getByRole("button", { name: "Save layout" }).click();
    await expect(page.getByRole("status")).toContainText("saved");
    await page.goto("/");
    await expect(page.getByRole("heading", { name: "Worn and loved" })).toBeVisible();
    await page.goto("/admin/banners");
    await page.locator(".section-editor article").filter({ hasText: "Testimonials" }).locator('input[type="checkbox"]').uncheck();
    await page.getByRole("button", { name: "Save layout" }).click();
  }
});
