test("admin builds, publishes, hides, and archives a category tree", async ({ page }, testInfo) => {
  const suffix = `${testInfo.project.name}-${Date.now()}`;
  const rootName = `Editorial ${suffix}`;
  const childName = `Linen ${suffix}`;
  await page.goto("/login?next=%2Fadmin%2Fcategories");
  await page.getByLabel("Email address").fill("admin@yoranzify.local");
  await page.getByLabel("Password", { exact: true }).fill("Yoranzify123!");
  await page.getByRole("button", { name: /Sign in/ }).click();
  await expect(page).toHaveURL(/\/admin\/categories$/);
  await page.getByRole("button", { name: "Add category" }).click();
  await page.getByLabel("Name").fill(rootName);
  await page.getByLabel("Description").fill("A considered edit for everyday dressing.");
  await page.getByRole("button", { name: "Save category" }).click();
  const rootRow = page.locator(".category-admin-row").filter({ hasText: rootName });
  await expect(rootRow).toBeVisible();
  await rootRow.getByRole("button", { name: `Add child to ${rootName}` }).click();
  await page.getByLabel("Name").fill(childName);
  await page.getByRole("button", { name: "Save category" }).click();
  const childRow = page.locator(".category-admin-row").filter({ hasText: childName });
  await expect(childRow).toBeVisible();
  const rootSlug = rootName.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  await page.goto(`/categories/${rootSlug}`);
  await expect(page.getByRole("heading", { name: rootName })).toBeVisible();
  await expect(page.getByRole("heading", { name: childName })).toBeVisible();
  await page.goto("/admin/categories");
  const publishedChildRow = page.locator(".category-admin-row").filter({ hasText: childName });
  await publishedChildRow.getByRole("button", { name: `Hide ${childName}` }).click();
  await expect(publishedChildRow).toContainText("Hidden");
  await page.goto(`/categories/${rootSlug}`);
  await expect(page.getByRole("heading", { name: childName })).toHaveCount(0);
  await page.goto("/admin/categories");
  page.on("dialog", (dialog) => dialog.accept());
  const hiddenChildRow = page.locator(".category-admin-row").filter({ hasText: childName });
  await hiddenChildRow.getByRole("button", { name: `Archive ${childName}` }).click();
  await expect(hiddenChildRow).toHaveClass(/archived/);
  const finalRootRow = page.locator(".category-admin-row").filter({ hasText: rootName });
  await finalRootRow.getByRole("button", { name: `Archive ${rootName}` }).click();
  await expect(finalRootRow).toHaveClass(/archived/);
  await page.goto(`/categories/${rootSlug}`);
  await expect(page.getByRole("heading", { name: "That page slipped away." })).toBeVisible();
});

